def update_markdown(df, filename="README.md"):
    """Convert DataFrame to Markdown and write the schedule page."""
    with open(filename, 'w', encoding='utf-8') as f:

        df = df.fillna("")
        f.write("# BMI PhD Student Meeting Schedule — Fall 2026\n\n")
        f.write("> _Auto-generated from the BMI Google Sheet — do not edit this file by hand._\n\n")
        f.write("**To update, see [how-to-update.md](how-to-update.md).**\n\n")

        f.write(df.to_markdown(index=False))
        f.write("\n")
    print(f"{filename} has been updated.")

