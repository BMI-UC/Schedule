import pandas as pd
import requests
import io

def fetch_google_sheet_csv(url, sheet_name=None):
    """Fetch CSV data from a specific sheet in a Google Sheet."""
    if sheet_name:
        sheet_url = f"{url}&sheet={sheet_name}"
    else:
        sheet_url = url
    response = requests.get(sheet_url)
    response.raise_for_status()
    # Google's CSV export declares no charset, so requests falls back to
    # ISO-8859-1 and mangles accented characters. The export is always UTF-8.
    response.encoding = "utf-8"
    return pd.read_csv(io.StringIO(response.text))

